"""Generate Goal 27A per-material scrap textures from the upstream base texture.

Upstream ItemAutogen (items/special/ItemAutogen.java:51-71) recolours
``textures/items/scraps.png`` at runtime for every material whose solidColorLight differs from
solidColorDark, with RGBMutatorInterpolatedComponentRemap(0xFFFFFF, 0x505050, light, dark). NEO has no
runtime sprite mutation, so this script applies the same per-component formula offline (Java truncation,
& 0xFF) and writes one texture per SMELTABLE/ADDITIVE material (ItemScraps.getSubItems). Same codec and
formula as tools/migration/goal10a_scrap_textures.py, which is not modified: its four textures (tungsten,
cobalt, steel, durasteel) are part of this set and must be reproduced byte-identically; they are only
checked here, never rewritten.

Exclusions: MAT_COPPER keeps the Goal 5A base model texture scraps.png; materials whose light and dark
colours are equal keep the uncoloured base icon (imported as scraps_plain.png); MAT_BISMUTH uses the
original override texture scraps_bismuth.png (ItemScraps registers it through .aot). The three original
icons scraps_additive.png, scraps_bismuth.png and scraps.png (as scraps_plain.png) are imported unchanged.

The embedded material table is asserted at run time against the original Mats.java declarations, so a later
upstream colour or factory change is reported instead of silently ignored.

Usage:
  python tools/migration/goal27a_scrap_textures.py            # write textures and imports
  python tools/migration/goal27a_scrap_textures.py --check    # compare only
"""

