FACTORY_BEHAVIOR = {"makeSmeltable": "SMELTABLE", "makeAdditive": "ADDITIVE"}
DECLARATION = re.compile(r"^\s*public static final NTMMaterial (MAT_\w+)\s*=\s*(make\w*)\((.*)")
HEX_COLOR = re.compile(r"0x[0-9A-Fa-f]{6}\b")

PNG_SIGNATURE = b"\x89PNG\r\n\x1a\n"


def _chunks(data: bytes):
    if not data.startswith(PNG_SIGNATURE):
        raise ValueError("not a PNG file")
    offset = len(PNG_SIGNATURE)
    while offset < len(data):
        length = struct.unpack(">I", data[offset:offset + 4])[0]
        kind = data[offset + 4:offset + 8]
        yield kind, data[offset + 8:offset + 8 + length]
        offset += 12 + length


def decode_rgba(path: Path) -> tuple[int, int, list[list[tuple[int, int, int, int]]]]:
    data = path.read_bytes()
    width = height = None
    idat = b""
    for kind, body in _chunks(data):
        if kind == b"IHDR":
            width, height, depth, color, _, _, interlace = struct.unpack(">IIBBBBB", body)
            if depth != 8 or color != 6 or interlace != 0:
                raise ValueError(f"{path}: only 8-bit non-interlaced RGBA is supported")
        elif kind == b"IDAT":
            idat += body
    raw = zlib.decompress(idat)
    stride = width * 4
    rows: list[bytearray] = []
    previous = bytearray(stride)
    position = 0
    for _ in range(height):
        filter_type = raw[position]
        line = bytearray(raw[position + 1:position + 1 + stride])
        position += 1 + stride
        for i in range(stride):
            left = line[i - 4] if i >= 4 else 0
            up = previous[i]
            upper_left = previous[i - 4] if i >= 4 else 0
            if filter_type == 1:
                line[i] = (line[i] + left) & 0xFF
            elif filter_type == 2:
                line[i] = (line[i] + up) & 0xFF
            elif filter_type == 3:
                line[i] = (line[i] + ((left + up) >> 1)) & 0xFF
            elif filter_type == 4:
                p = left + up - upper_left
                pa, pb, pc = abs(p - left), abs(p - up), abs(p - upper_left)
                predictor = left if pa <= pb and pa <= pc else up if pb <= pc else upper_left
                line[i] = (line[i] + predictor) & 0xFF
            elif filter_type != 0:
                raise ValueError(f"{path}: unknown PNG filter {filter_type}")
        rows.append(line)
        previous = line
    pixels = [[tuple(row[x * 4:x * 4 + 4]) for x in range(width)] for row in rows]
    return width, height, pixels


def encode_rgba(width: int, height: int, pixels) -> bytes:
    raw = b"".join(b"\x00" + bytes(c for pixel in row for c in pixel) for row in pixels)

    def chunk(kind: bytes, body: bytes) -> bytes:
        return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body) & 0xFFFFFFFF)

    header = struct.pack(">IIBBBBB", width, height, 8, 6, 0, 0, 0)
    return PNG_SIGNATURE + chunk(b"IHDR", header) + chunk(b"IDAT", zlib.compress(raw, 9)) + chunk(b"IEND", b"")


def _java_int(value: float) -> int:
    """Java's (int) cast of a double truncates toward zero."""
    return int(value)


def shift_component(lighter: int, darker: int, bound_lighter: int, bound_darker: int, component: int) -> int:
    position = (component - bound_lighter) / (bound_darker - bound_lighter)
    return _java_int(lighter + position * (darker - lighter)) & 0xFF


def remap(pixel, light: int, dark: int):
    r, g, b, a = pixel
    channels = []
    for shift, value in ((16, r), (8, g), (0, b)):
        channels.append(shift_component((light >> shift) & 0xFF, (dark >> shift) & 0xFF,
                                        (SOURCE_LIGHT >> shift) & 0xFF, (SOURCE_DARK >> shift) & 0xFF, value))
    return channels[0], channels[1], channels[2], a


def render(base, light: int, dark: int) -> bytes:
    width, height, pixels = base
    return encode_rgba(width, height, [[remap(pixel, light, dark) for pixel in row] for row in pixels])


def verify_against_upstream() -> list[str]:
    """Compare the embedded table with Mats.java; returns problem descriptions."""
    declared = {}
    for line in MATS_JAVA.read_text(encoding="utf-8", errors="replace").splitlines():
        match = DECLARATION.match(line)
        if match:
            colors = [int(c, 16) for c in HEX_COLOR.findall(match.group(3))]
            if len(colors) == 1:
                colors = colors * 3  # makeSmeltable(id, dict, color) uses one colour for light, dark and molten
            declared[match.group(1)] = (match.group(2), colors)
    problems = []
    for field, _name, behavior, light, dark in MATERIALS:
        if field not in declared:
            problems.append(f"{field}: not declared in Mats.java")
            continue
        factory, colors = declared[field]
        if FACTORY_BEHAVIOR.get(factory) != behavior:
            problems.append(f"{field}: factory {factory} does not give {behavior}")
        if len(colors) < 2 or colors[0] != light or colors[1] != dark:
            problems.append(f"{field}: Mats.java colours {[hex(c) for c in colors[:2]]} != table {hex(light)}/{hex(dark)}")
    listed = {field for field, *_ in MATERIALS}
    for field, (factory, _colors) in declared.items():
        if factory in FACTORY_BEHAVIOR and field not in listed:
            problems.append(f"{field}: {factory} material missing from the table")
    return problems


def plan():
    """(file suffix, light, dark) for every material that gets a recoloured texture."""
    result = []
    for field, name, _behavior, light, dark in MATERIALS:
        if field in SKIPPED_FIELDS or light == dark:
            continue
        result.append((name.lower(), light, dark))
    suffixes = [suffix for suffix, _, _ in result]
    if len(set(suffixes)) != len(suffixes):
        raise ValueError("duplicate texture name in the material table")
    return result


def rel(path: Path) -> str:
    return path.relative_to(NEO_ROOT).as_posix()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only verify that the committed textures match")
    args = parser.parse_args()
    for path in [SOURCE, MATS_JAVA] + [UPSTREAM_ITEMS / source for source, _ in IMPORTS]:
        if not path.is_file():
            print(f"missing upstream file {path}", file=sys.stderr)
            return 2
    problems = verify_against_upstream()
    if problems:
        for problem in problems:
            print(f"UPSTREAM-DRIFT {problem}", file=sys.stderr)
        return 2

    base = decode_rgba(SOURCE)
    expected = [(suffix, render(base, light, dark)) for suffix, light, dark in plan()]
    status = {"OK": 0, "MISSING": 0, "MISMATCH": 0}

    def compare(target: Path, content: bytes) -> str:
        if not target.is_file():
            return "MISSING"
        return "OK" if target.read_bytes() == content else "MISMATCH"

    # The Goal 10A textures must come out byte-identical before anything is written.
    for suffix, content in expected:
        if suffix in GOAL10A_EXISTING:
            target = TARGET_DIR / f"scraps_{suffix}.png"
            result = compare(target, content)
            if result != "OK":
                print(f"{result} {rel(target)} (Goal 10A texture is not reproduced; stopping)", file=sys.stderr)
                return 3
    present = {suffix for suffix, _ in expected} & GOAL10A_EXISTING
    if present != GOAL10A_EXISTING:
        print(f"Goal 10A set {sorted(GOAL10A_EXISTING - present)} is not part of the plan", file=sys.stderr)
        return 3

    for suffix, content in expected:
        target = TARGET_DIR / f"scraps_{suffix}.png"
        result = compare(target, content)
        if args.check:
            status[result] += 1
            print(f"{result} {rel(target)}")
        elif suffix in GOAL10A_EXISTING:
            status["OK"] += 1
            print(f"unchanged {rel(target)}")
        else:
            target.write_bytes(content)
            print(f"wrote {rel(target)}")
    for source, name in IMPORTS:
        target = TARGET_DIR / name
        content = (UPSTREAM_ITEMS / source).read_bytes()
        result = compare(target, content)
        if args.check:
            status[result] += 1
            print(f"{result} {rel(target)} (import of {source})")
        else:
            target.write_bytes(content)
            print(f"wrote {rel(target)} (import of {source})")
    if args.check:
        print(f"summary: {status}")
    return 1 if args.check and (status["MISSING"] or status["MISMATCH"]) else 0


if __name__ == "__main__":
    raise SystemExit(main())
