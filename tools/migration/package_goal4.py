"""Verify the final Goal 4 JAR against current outputs, then retain a named copy."""
from pathlib import Path
import hashlib
import json
import shutil
import zipfile

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "build/migration/goal4"
JAR = ROOT / "build/libs/hbmsntm-198A.jar"
RELEASE = ROOT / "build/migration/releases/goal4"


def sha(data):
    return hashlib.sha256(data).hexdigest()


def main():
    generated = json.loads((OUT / "generated-check.json").read_text(encoding="utf-8"))
    stamp = json.loads((ROOT / "src/generated/resources/.migration-stamp.json").read_text(encoding="utf-8"))
    asset_review = json.loads((ROOT / "migration/goal4-resource-ownership.json").read_text(encoding="utf-8"))
    checked = []
    with zipfile.ZipFile(JAR) as jar:
        names = jar.namelist()
        assert len(names) == len(set(names)), "duplicate ZIP paths"
        assert not any(n.startswith(("tools/", "migration/")) or "/.cache/" in n or ".migration-stamp" in n for n in names), "verification files in JAR"
        for name in stamp["generated"]:
            expected = (ROOT / "src/generated/resources" / name).read_bytes()
            assert jar.read(name) == expected, f"generated bytes differ: {name}"
        for asset in asset_review["reused_assets"]:
            path = ROOT / asset["target_path"]
            name = path.relative_to(ROOT / "src/main/resources").as_posix()
            assert sha(path.read_bytes()) == asset["target_sha256"], name
            assert jar.read(name) == path.read_bytes(), name
            checked.append(name)
        name = "assets/hbmsntm/lang/zh_cn.json"
        assert jar.read(name) == (ROOT / "src/main/resources" / name).read_bytes(), name
        checked.append(name)
        for source in generated["changed_inputs"]:
            if source.startswith("src/main/java/") and source.endswith(".java"):
                name = source.removeprefix("src/main/java/").removesuffix(".java") + ".class"
                assert jar.read(name) == (ROOT / "build/classes/java/main" / name).read_bytes(), name
                checked.append(name)
        previous = ROOT / "build/migration/releases/goal3c/hbmsntm-198A-goal3c.jar"
        with zipfile.ZipFile(previous) as old:
            old_names, new_names = set(old.namelist()), set(names)
            delta = {"added": sorted(new_names - old_names), "removed": sorted(old_names - new_names),
                     "modified": sorted(n for n in old_names & new_names if old.read(n) != jar.read(n))}
    expected_added = generated["generated_added"]
    expected_modified = sorted(set(checked) - {a["target_path"].removeprefix("src/main/resources/") for a in asset_review["reused_assets"]}
                               | set(generated["generated_modified"]))
    assert delta["added"] == expected_added and not delta["removed"], delta
    assert delta["modified"] == expected_modified, (delta["modified"], expected_modified)
    data = JAR.read_bytes()
    digest = sha(data)
    RELEASE.mkdir(parents=True, exist_ok=True)
    destination = RELEASE / "hbmsntm-198A-goal4.jar"
    if destination.exists() and destination.read_bytes() != data:
        raise RuntimeError("Existing named Goal 4 release differs; preserve it before a new named delivery")
    shutil.copy2(JAR, destination)
    assert sha(destination.read_bytes()) == digest
    (RELEASE / "SHA256SUMS.txt").write_text(f"{digest}  {destination.name}\n", encoding="utf-8")
    report = {"file": destination.name, "bytes": len(data), "sha256": digest,
              "source_commit": "9593d7f84a5b52da810ffe50e559873334acaa49",
              "neo_commit": "4320fb9153754a8b09cc208124b88a16a3e6c27a",
              "generated_files_compared": len(stamp["generated"]), "additional_bytes_compared": checked,
              "goal3c_delta": delta, "changed_inputs": generated["changed_inputs"],
              "boundary": "Local implementation, isolated production-code regression, generated/build/JAR checks only. User gameplay, real saves, multiplayer and dedicated server remain unverified."}
    text = json.dumps(report, ensure_ascii=False, indent=2) + "\n"
    (RELEASE / "release.json").write_text(text, encoding="utf-8")
    (OUT / "release.json").write_text(text, encoding="utf-8")
    print(f"{destination}\n{len(data)} bytes\nSHA-256 {digest}")
    print(f"Compared {len(stamp['generated'])} generated files and {len(checked)} additional resources/classes; delta +{len(delta['added'])} ~{len(delta['modified'])} -{len(delta['removed'])}")


if __name__ == "__main__":
    main()
